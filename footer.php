<script>
    const cvInput = document.getElementById('cv-upload');
    const dropzone = document.querySelector('.cv-dropzone');
    const selectedFile = document.getElementById('selected-file');

    function assignFile(file) {
        if (!cvInput || !file) return;
        const transfer = new DataTransfer();
        transfer.items.add(file);
        cvInput.files = transfer.files;
        validateFile(file);
    }

    cvInput?.addEventListener('change', function() {
        if (this.files.length > 0) {
            validateFile(this.files[0]);
        }
    });

    dropzone?.addEventListener('dragover', function(e) {
        e.preventDefault();
        dropzone.classList.add('dragover');
    });

    dropzone?.addEventListener('dragleave', function() {
        dropzone.classList.remove('dragover');
    });

    dropzone?.addEventListener('drop', function(e) {
        e.preventDefault();
        dropzone.classList.remove('dragover');
        const file = e.dataTransfer.files[0];
        if (file) {
            assignFile(file);
        }
    });

    function validateFile(file) {

        const allowedExtensions = ['pdf', 'doc', 'docx', 'jpg', 'jpeg', 'png', 'webp'];

        const extension = file.name
            .split('.')
            .pop()
            .toLowerCase();

        // Check extension
        if (!allowedExtensions.includes(extension)) {

            selectedFile.textContent =
                'Please upload a PDF, DOC, DOCX, JPG, JPEG, PNG, WEBP file.';

            selectedFile.style.color = '#e53935';

            cvInput.value = '';

            return false;
        }

        // Check 10MB
        if (file.size > 10 * 1024 * 1024) {

            selectedFile.textContent =
                'File size must be less than 10MB.';

            selectedFile.style.color = '#e53935';

            cvInput.value = '';

            return false;
        }

        // Valid file
        selectedFile.textContent =
            'Selected: ' + file.name;

        selectedFile.style.color = '#7c3aed';
        return true;
    }
</script>

